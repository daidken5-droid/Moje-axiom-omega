// Screenshoty všech obrazovek: node shoot.js <out-dir>
const { chromium } = require('playwright');
const path = require('path');
(async () => {
  const outDir = process.argv[2] || '/tmp/preview';
  const base = 'file://' + path.join(__dirname, 'out', 'index.html');
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 412, height: 892 }, deviceScaleFactor: 2 });
  const p = await ctx.newPage();
  const errors = [];
  p.on('pageerror', e => errors.push(e.message));
  p.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
  const shot = async n => { await p.waitForTimeout(250); await p.screenshot({ path: `${outDir}/${n}.png` }); };
  await p.goto(base + '?welcome'); await shot('01-welcome');
  await p.goto(base); await shot('02-chat');
  await p.evaluate(() => { threadId = 0; msgs = []; live = null; render(); }); await shot('03-empty');
  await p.evaluate(() => { __live(); loadThread(2); omegaReceive('phase', { text: 'Agent · krok 3/10 · Gemma 4' }); omegaReceive('step', { index: 1, tool: 'web_search', thought: 'Hledám dodavatele' }); omegaReceive('step', { index: 2, tool: 'fetch_url', thought: 'Čtu ceník' }); omegaReceive('stream', { text: 'Porovnávám ceny…', reasoning: '' }); }); await shot('04-agent-live');
  await p.evaluate(() => { live = null; go('agents'); }); await shot('05-agents');
  await p.evaluate(() => { loadThread(3); go('chat'); }); await shot('04b-code');
  await p.evaluate(() => { loadThread(1); go('chat'); document.querySelector('details.thought').open = true; }); await shot('04c-thought');
  await p.evaluate(() => { const m = document.querySelector('#main'); m.scrollTop = m.scrollHeight; }); await shot('25-evidence-chip');
  await p.evaluate(() => { evidenceSheet(msgs.find(x => x.role !== 'user')); }); await shot('26-evidence-map');
  await p.evaluate(() => closeSheet());
  await p.evaluate(() => go('modules')); await p.click('[data-hf-search]'); await p.waitForTimeout(200); await shot('06-modules');
  await p.evaluate(() => window.scrollTo(0, 0)); await p.evaluate(() => { const m = document.querySelector('#main'); m.scrollTop = m.scrollHeight; }); await shot('07-modules-bottom');
  await p.evaluate(() => { memTab = 'kb'; go('memory'); }); await shot('08-offline-db');
  await p.evaluate(() => { memTab = 'mem'; go('memory'); }); await shot('09-memory');
  await p.evaluate(() => go('system')); await shot('10-system');
  await p.evaluate(() => { go('chat'); kindSheet(); }); await shot('11-kind');
  await p.evaluate(() => { closeSheet(); selfSheet(); }); await shot('12-self');
  await p.evaluate(() => { closeSheet(); loadThread(4); live = null; go('chat'); }); await shot('15-apk');
  await p.evaluate(() => { loadThread(5); go('chat'); }); await shot('21-pipeline');
  await p.evaluate(() => { go('modules'); const d = [...document.querySelectorAll('.eyebrow')].find(e => e.textContent.includes('DOLADĚNÍ')); d && d.scrollIntoView(); }); await shot('22-doladeni');
  await p.evaluate(() => { variant = 'STUDIO'; kindSheet(); }); await shot('16-variants');
  await p.evaluate(() => { const o = Omega.state; Omega.state = () => { const j = JSON.parse(o()); j.job.busy = false; return JSON.stringify(j); }; closeSheet(); variant = 'AUTO'; threadId = 0; msgs = []; live = null; go('chat'); });
  await p.fill('#input', 'Vytvoř mi aplikaci APK na evidenci tankování'); await p.waitForTimeout(500); await shot('17-randy-hint');
  await p.evaluate(() => go('system')); await shot('18-randy-panel');
  await p.evaluate(() => { go('chat'); selfSheet(); }); await shot('19-vedomi');
  await p.evaluate(() => { closeSheet(); go('system'); }); await shot('23-pixel-vykon');
  await p.evaluate(() => { go('chat'); selfSheet(); });
  await p.evaluate(() => { const s = document.querySelector('.sheet'); s.scrollTop = 900; }); await shot('20-vedomi-denik');
  await p.goto(base + '?theme=platinum'); await shot('13-platinum');
  console.log(errors.length ? 'ERRORS:\n' + errors.join('\n') : 'no js errors');
  await b.close();
})();
